// Pine indicators from the repo's indicators/ folder, plus a generated "TVE All-in-One" that contains all of them.
// launch.mjs pulls the folder from GitHub at each start and gives the list to the panel's Indicators tab,
// which saves them as private scripts in your TradingView account (Indicators > My scripts).
//   node indicators.mjs           pull from GitHub, then print what's there
//   node indicators.mjs --build   also write "indicators/TVE All-in-One.pine" (for copy/paste)
//   node indicators.mjs --save    save/update all of them in your account (TradingView must be running via the launcher)
//
// Writing your own: one indicator per .pine file in indicators/. Put the line "// @tve-body" after the
// indicator(...) call; everything below it goes into the All-in-One, so start your variable and function
// names with a short prefix of their own (fp_, og_, ...) so they can't clash with another indicator's.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const DIR = join(here, 'indicators');
export const ALL_IN_ONE = 'TVE All-in-One';
const SAFE = /^[\w][\w .()-]*\.pine$/;

// GitHub repo from update.json's raw URL (https://raw.githubusercontent.com/<owner>/<repo>/<branch>/).
function repo() {
  try {
    const { source } = JSON.parse(readFileSync(join(here, 'update.json'), 'utf8'));
    const m = /^https:\/\/raw\.githubusercontent\.com\/([\w.-]+)\/([\w.-]+)\/([\w.\/-]+?)\/?$/.exec(source);
    return m && { owner: m[1], name: m[2], branch: m[3] };
  } catch { return null; }
}

// Downloads every .pine file in the repo's indicators/ folder. Files that are only on this PC are kept.
export async function pull() {
  const r = repo();
  if (!r) return 'no repo in update.json';
  try {
    const api = `https://api.github.com/repos/${r.owner}/${r.name}/contents/indicators?ref=${encodeURIComponent(r.branch)}`;
    const res = await fetch(api, { headers: { 'User-Agent': 'TradingView-Enhanced' }, signal: AbortSignal.timeout(8000) });
    if (res.status === 404) return 'no indicators folder in the repo';
    if (!res.ok) throw new Error(`GitHub HTTP ${res.status}`);
    const files = (await res.json()).filter(f => f.type === 'file' && SAFE.test(f.name) && f.name !== `${ALL_IN_ONE}.pine`);
    const got = await Promise.all(files.map(async f => {
      const t = await fetch(f.download_url, { signal: AbortSignal.timeout(8000) });
      if (!t.ok) throw new Error(`${f.name}: HTTP ${t.status}`);
      return [f.name, await t.text()];
    }));
    mkdirSync(DIR, { recursive: true });
    for (const [name, text] of got) writeFileSync(join(DIR, name), text);
    return `pulled ${got.length}`;
  } catch (e) {
    return `pull skipped: ${e.message}`;
  }
}

const meta = src => ({
  title: /indicator\(\s*"([^"]+)"/.exec(src)?.[1],
  description: /^\/\/\s*@description\s+(.*)$/m.exec(src)?.[1] || '',
});

// The part of a script that goes into the All-in-One: after "// @tve-body", or, for scripts without the
// marker, everything except the //@version line and the indicator(...) call.
function body(src) {
  const lines = src.replace(/\r\n/g, '\n').split('\n');
  const i = lines.findIndex(l => /^\s*\/\/\s*@tve-body/.test(l));
  if (i >= 0) return lines.slice(i + 1).join('\n');
  let rest = lines.filter(l => !/^\s*\/\/@version/.test(l)).join('\n');
  const start = rest.search(/^indicator\s*\(/m);
  if (start >= 0) {
    let depth = 0, j = start;
    for (; j < rest.length; j++) {
      if (rest[j] === '(') depth++;
      else if (rest[j] === ')' && --depth === 0) break;
    }
    rest = rest.slice(0, start) + rest.slice(j + 1);
  }
  return rest;
}

export function build(list) {
  const parts = list.map(x => `\n// ═════ ${x.title} (${x.file}) ═════\n${body(x.source).trim()}\n`);
  return [
    '//@version=6',
    `// @description Every TVE indicator in one script: ${list.map(x => x.title).join(', ')}. Each one's parts can be turned on and off in Settings. Generated by TradingView Enhanced; edit the separate indicators, not this.`,
    `indicator("${ALL_IN_ONE}", "TVE", overlay = true, max_boxes_count = 500, max_lines_count = 500, max_labels_count = 500)`,
    ...parts,
  ].join('\n');
}

// Everything in the local folder (after pull), plus the All-in-One built from them.
export function load() {
  if (!existsSync(DIR)) return [];
  const list = readdirSync(DIR).filter(f => SAFE.test(f) && f !== `${ALL_IN_ONE}.pine`).sort().map(file => {
    const source = readFileSync(join(DIR, file), 'utf8').replace(/\r\n/g, '\n');
    return { file, source, ...meta(source) };
  }).filter(x => x.title);
  if (list.length > 1) list.push({ file: `${ALL_IN_ONE}.pine`, source: build(list), ...meta(build(list)), allInOne: true });
  return list;
}

// Runs inside the TradingView page with its logged-in session. Saves each script as a private script,
// updating the one with the same name if it's already there. mode 'check' only compiles.
export async function pageSave(list, mode) {
  const PINE = window.PINE_URL || 'https://pine-facade.tradingview.com/pine-facade';
  const call = async (path, source) => {
    const r = await fetch(PINE + path, { method: 'POST', credentials: 'include', body: new URLSearchParams({ source }) });
    const j = await r.json().catch(() => null);
    if (!r.ok || !j) throw new Error(`HTTP ${r.status}`);
    return j;
  };
  const errorsOf = j => {
    const errs = j.reason2?.errors || j.result?.errors || j.reason?.errors || [];
    return errs.map(e => `line ${e.start?.line}: ${(e.message || '').replace(/\{(\w+)\}/g, (_, k) => e.ctx?.[k] ?? k)}`);
  };
  let saved = [];
  if (mode !== 'check') {
    const r = await fetch(PINE + '/list/?filter=saved', { credentials: 'include' });
    saved = r.ok ? await r.json() : [];
  }
  const out = [];
  for (const s of list) {
    try {
      const c = await call(`/translate_light/?v=3`, s.source);
      const errs = errorsOf(c);
      if (errs.length) { out.push({ title: s.title, ok: false, text: `has errors, not saved:\n  ${errs.slice(0, 5).join('\n  ')}` }); continue; }
      if (mode === 'check') { out.push({ title: s.title, ok: true, text: 'compiles' }); continue; }
      const have = saved.find(x => x.scriptName === s.title);
      const j = have
        ? await call(`/save/next/${encodeURIComponent(have.scriptIdPart)}?allow_create_new=false`, s.source)
        : await call(`/save/new?name=${encodeURIComponent(s.title)}`, s.source);
      if (j.success === false) throw new Error(errorsOf(j).join('; ') || JSON.stringify(j.reason || j).slice(0, 200));
      out.push({ title: s.title, ok: true, text: have ? 'updated' : 'saved' });
    } catch (e) {
      out.push({ title: s.title, ok: false, text: `failed: ${e.message}` });
    }
  }
  return out;
}

if (process.argv[1]?.endsWith('indicators.mjs')) {
  console.log(await pull());
  const list = load();
  for (const x of list) console.log(`${x.allInOne ? '*' : '-'} ${x.title}  (${x.file})`);
  if (process.argv.includes('--build')) {
    const aio = list.find(x => x.allInOne);
    if (aio) { writeFileSync(join(DIR, aio.file), aio.source); console.log(`wrote indicators/${aio.file}`); }
  }
  const mode = process.argv.includes('--save') ? 'save' : process.argv.includes('--check') ? 'check' : null;
  if (mode) {
    let targets;
    try { targets = await (await fetch('http://127.0.0.1:9222/json/list')).json(); } catch {
      console.log('TradingView is not running with the launcher.'); process.exit(1);
    }
    const page = targets.find(t => t.type === 'page' && /tradingview\.com/.test(t.url));
    if (!page) { console.log('No TradingView chart tab found.'); process.exit(1); }
    const ws = new WebSocket(page.webSocketDebuggerUrl);
    ws.onopen = () => ws.send(JSON.stringify({ id: 1, method: 'Runtime.evaluate', params: {
      expression: `(${pageSave})(${JSON.stringify(list)}, ${JSON.stringify(mode)})`, awaitPromise: true, returnByValue: true } }));
    ws.onmessage = e => {
      const m = JSON.parse(e.data);
      if (m.id !== 1) return;
      const v = m.result?.result?.value;
      console.log(v ? v.map(r => `${r.ok ? 'ok  ' : 'FAIL'} ${r.title}: ${r.text}`).join('\n') : JSON.stringify(m.result));
      ws.close();
      process.exitCode = v?.every(r => r.ok) ? 0 : 1;
    };
  }
}
